/** Ancho de un carácter desconocido (milésimas de em). */
const UNKNOWN_WIDTH = 556;

/** Ancho en puntos de `s` a tamaño `fontSize`. Cada carácter (punto de código) cuenta una vez. */
export function textWidth(s: string, fontSize: number): number {
  let units = 0;
  for (const ch of s) {
    units += HELVETICA_WIDTHS[ch] ?? UNKNOWN_WIDTH;
  }
  return (units * fontSize) / 1000;
}
